"""
41_remediation_threshold.py

Option 4 of the "size the omitted channel" problem: instead of putting a price on
conflict, invert the question. Ask what a riot-affected place-year would have to be
worth for site remediation to pay for itself on the CONFLICT channel alone, and compare
that threshold with published per-site remediation costs. The reader then supplies their
own valuation.

This avoids valuing violence, which is where the alternative approaches break down: the
one published decomposition that prices lead's crime channel (Gould 2009) counts only
direct criminal-justice costs and so puts it at roughly 1% of the earnings channel, which
is not the relevant cost concept for riot deaths in low-income settings.

Inputs:
  - our own attributable place-years (from the extensive-margin aggregation)
  - published per-site remediation costs for informal ULAB sites in LMICs:
      Bangladesh        $40,300   Chowdhury et al. (2021)
      Vietnam          $118,750   Ericson et al. (2018), GeoHealth
      Dominican Rep.   $430,000   Ericson et al. (2018), GeoHealth
    These are project totals for single residential sites, not programme budgets.

Key bound: a place-year with a riot death contains at least one death by construction, so
deaths averted >= place-years averted, and the cost per DEATH averted is at most the cost
per riot-death place-year. That makes the comparison one-sided in the conservative
direction without needing a value of statistical life.

Outputs (+ Overleaf): output/tables/remediation_values.tex, output/tables/tab_remediation.tex
"""

from config import TABLES, POST_YR, END_YR, save_to_overleaf

# ── our estimates, read from generated_values.tex (written by 11_generate_values.py
#    from 29_extensive_margin_main.py), so this script cannot drift from the paper ──
import re
_gv = (TABLES / "generated_values.tex").read_text(encoding="utf-8")
def _macro(name):
    m = re.search(r"\\newcommand\{\\" + name + r"\}\{([^}]*)\}", _gv)
    if not m:
        raise SystemExit(f"{name} missing from generated_values.tex; run 11_generate_values.py first")
    return int(m.group(1).replace(",", ""))
RIOT_PY  = _macro("botecRiots")        # additional place-years with a riot, 2007-END_YR
DEATH_PY = _macro("botecFatalities")   # additional place-years with a riot death
N_SITES  = _macro("nBatTotal")         # documented battery sites in the three countries
YEARS     = END_YR - POST_YR + 1

COSTS = [("Bangladesh", 40_300), ("Vietnam", 118_750), ("Dominican Republic", 430_000)]
HORIZONS = (10, 20)

per_site_riot  = RIOT_PY / N_SITES / YEARS      # riot place-years per site-year
per_site_death = DEATH_PY / N_SITES / YEARS     # riot-death place-years per site-year
print(f"Attributable per site per year: {per_site_riot:.2f} riot place-years, "
      f"{per_site_death:.2f} riot-death place-years")
print(f"(from {RIOT_PY:,} and {DEATH_PY} across {N_SITES} sites over {YEARS} years)\n")

print("Break-even value of one averted riot-death place-year, by remediation cost and horizon:")
print(f"  {'site cost':>28s}  " + "  ".join(f"{h:>2d}-yr horizon" for h in HORIZONS))
rows = []
for label, c in COSTS:
    vals = [c / (per_site_death * h) for h in HORIZONS]
    rows.append((label, c, vals))
    print(f"  {label:>18s} ${c:>7,}  " + "  ".join(f"${v:>11,.0f}" for v in vals))

lo = min(v for _, _, vs in rows for v in vs)
hi = max(v for _, _, vs in rows for v in vs)
print(f"\nRange across all cost/horizon combinations: ${lo:,.0f} to ${hi:,.0f}")
print("Interpretation: remediation pays for itself on the conflict channel alone if one")
print("averted riot-death place-year is worth more than this. Because such a place-year")
print("contains at least one death, the implied cost per death averted is no higher.")

v = ["% auto-generated by 41_remediation_threshold.py",
     r"\newcommand{\remPerSiteRiot}{" + f"{per_site_riot:.3f}" + "}",
     r"\newcommand{\remPerSiteDeath}{" + f"{per_site_death:.3f}" + "}",
     r"\newcommand{\remCostLo}{" + f"{COSTS[0][1]:,}" + "}",
     r"\newcommand{\remCostHi}{" + f"{COSTS[-1][1]:,}" + "}",
     r"\newcommand{\remHorizonLo}{" + f"{HORIZONS[0]}" + "}",
     r"\newcommand{\remHorizonHi}{" + f"{HORIZONS[1]}" + "}"]
(TABLES / "remediation_values.tex").write_text("\n".join(v) + "\n", encoding="utf-8")
save_to_overleaf("remediation_values.tex", str(TABLES / "remediation_values.tex"), subfolder="tables")
print("\nSaved: remediation_values.tex")

# ── Appendix table ────────────────────────────────────────────────────────────
SRC = {"Bangladesh": r"\citet{chowdhury2021}", "Vietnam": r"\citet{ericson2018cost}",
       "Dominican Republic": r"\citet{ericson2018cost}"}
t = [r"\begin{table}[htbp]",
     r"\caption{Break-Even Value of an Averted Riot-Death Place-Year}", r"\label{tab:remediation}",
     r"\begin{threeparttable}", r"\small", r"\begin{tabular}{llrrr}", r"\toprule",
     r"Site in & Source & Cost (US\$) & "
     + " & ".join(f"{h} years" for h in HORIZONS) + r" \\", r"\midrule"]
for label, c, vs in rows:
    t.append(f"{label} & {SRC[label]} & {c:,} & " + " & ".join(f"{v:,.0f}" for v in vs) + r" \\")
t += [r"\bottomrule", r"\end{tabular}", r"\begin{tablenotes}\setstretch{1}\footnotesize",
      # Table note lives in main.tex (\setTabNote{tab_remediation}{...}).
      r"\item \TabNote{tab_remediation}",
      r"\end{tablenotes}", r"\end{threeparttable}", r"\end{table}"]
(TABLES / "tab_remediation.tex").write_text("\n".join(t), encoding="utf-8")
save_to_overleaf("tab_remediation.tex", str(TABLES / "tab_remediation.tex"), subfolder="tables")
print("Saved: tab_remediation.tex")
