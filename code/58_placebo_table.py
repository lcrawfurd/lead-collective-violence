#!/usr/bin/env python3
"""
58_placebo_table.py -- Placebo tests on the main design (tab:placebo)
==============================================================================
Main design as in 55_binary_main_table.py: bt = 1[within 5 km of a battery site] x Post,
nt = the same for non-lead TSIP sites, one regression, lead-specific gap = bt - nt;
cell + year FE by country, cell + country x year FE pooled; SEs CRV1 on 1-degree
blocks (t(G-1) stars) and a wild cluster restricted bootstrap p for each gap.

  Panel A  Fake onset: pre-period only (1997-2006), Post = 1[year >= 2002];
           outcome 1[any riot].
  (ACLED strategic developments were dropped on 2026-10-23: most are security responses to
  organised conflict, e.g. curfews, arrests, weapons seizures and peace deals, so they are
  not a clean measure of reporting.)

Outputs
  output/tables/tab_placebo.tex            (+ Overleaf)
  output/tables/placebo_values.tex         (macros, prefix plc; + Overleaf)
"""
import numpy as np
import pandas as pd
import pyfixest as pf

from config import PANELS, TABLES, POST_YR, save_to_overleaf
from utils import add_block, lincom, wild_p, stars

NEAR5 = 1.0 / 6.0
FAKE_YR = 2002
COUNTRIES = [("Kenya", "Ke"), ("Ghana", "Gh"), ("Senegal", "Se")]

PAN = {}
for cn, _ in COUNTRIES:
    p = pd.read_parquet(PANELS / f"panel_{cn.lower()}.parquet").copy()
    p["country"] = cn
    p["cell_id_str"] = cn[:2] + "_" + p.cell_id.astype(str)
    p["cty_year"] = cn + "_" + p.year.astype(str)
    add_block(p, cn)
    p["bat5"] = (p.inv_dist_battery > NEAR5).astype(float)
    p["nl5"] = (p.inv_dist_nonlead > NEAR5).astype(float)
    PAN[cn] = p
PAN["Pooled"] = pd.concat(PAN.values(), ignore_index=True)


def gap(d, ycol, onset, pooled):
    d = d.copy()
    d["y"] = (d[ycol] > 0).astype(float)
    post = (d.year >= onset).astype(float)
    d["bt"], d["nt"] = d.bat5 * post, d.nl5 * post
    fe = ["cell_id_str", "cty_year" if pooled else "year"]
    m = pf.feols("y ~ bt + nt | " + " + ".join(fe), data=d, vcov={"CRV1": "block"})
    g, s, p = lincom(m, {"bt": 1, "nt": -1})
    return g, s, p, wild_p(d, "y", ["bt", "nt"], {"bt": 1, "nt": -1}, fe)


PANELS_ = [("Fake", r"Fake onset in 2002, pre-period only (1997--2006); any riot",
            lambda d, pooled: gap(d[d.year < POST_YR], "n_riots", FAKE_YR, pooled))]
COLS = ["Kenya", "Ghana", "Senegal", "Pooled"]
R, M = {}, {}
for key, _, f in PANELS_:
    for cn in COLS:
        R[(key, cn)] = f(PAN[cn], cn == "Pooled")
        g, s, p, wp = R[(key, cn)]
        tag = {"Kenya": "Ke", "Ghana": "Gh", "Senegal": "Se", "Pooled": "Pooled"}[cn]
        if cn == "Pooled":                   # the text quotes the pooled gaps only
            M[f"plc{key}Gap{tag}"] = f"{g:.3f}"
            M[f"plc{key}Gap{tag}WildP"] = f"{wp:.3f}"
        print(f"{key:6s} {cn:8s} gap {g:+.3f} ({s:.3f}) p={p:.3f} wild p={wp:.3f}")

L = [r"\begin{table}[H]", r"\caption{Placebo Test: Fake Onset in 2002 (Lead-Specific Gap, Main Design)}",
     r"\label{tab:placebo}", r"\begin{threeparttable}", r"\footnotesize",
     r"\begin{tabular}{lcccc}", r"\toprule",
     r" & Kenya & Ghana & Senegal & Pooled \\", r"\midrule"]
for key, title, _ in PANELS_:
    L.append(r"\multicolumn{5}{l}{\textit{" + title + r"}} \\[2pt]")
    L.append(r"\quad Lead-specific gap & " + " & ".join(
        f"{R[(key, c)][0]:.3f}{stars(R[(key, c)][3])}" for c in COLS) + r" \\")  # stars from the wild bootstrap p
    L.append(" & " + " & ".join(f"({R[(key, c)][1]:.3f})" for c in COLS) + r" \\")
    L.append(r"\quad Wild bootstrap $p$ & " + " & ".join(
        f"[{R[(key, c)][3]:.3f}]" for c in COLS) + r" \\[4pt]")
L += [r"\bottomrule", r"\end{tabular}", r"\begin{tablenotes}[flushleft]", r"\setstretch{1}\footnotesize",
      # Table note lives in main.tex (\setTabNote{tab_placebo}{...}).
      r"\item \TabNote{tab_placebo}",
      r"\end{tablenotes}", r"\end{threeparttable}", r"\end{table}"]
L = [x.replace("-0.", "$-$0.") if not x.startswith("\\") or "&" in x else x for x in L]
(TABLES / "tab_placebo.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
save_to_overleaf("tab_placebo.tex", str(TABLES / "tab_placebo.tex"), subfolder="tables")

lines = ["% Generated by 58_placebo_table.py -- do not edit by hand"]
for k, v in M.items():
    v = "$-$" + v[1:] if v.startswith("-") else v
    lines.append(r"\newcommand{\%s}{%s}" % (k, v))
(TABLES / "placebo_values.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
save_to_overleaf("placebo_values.tex", str(TABLES / "placebo_values.tex"), subfolder="tables")
print(f"Saved tab_placebo.tex and placebo_values.tex ({len(M)} macros)")
