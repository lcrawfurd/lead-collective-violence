"""
46_acled_descriptive.py  --  Slide figure: conflict in sub-Saharan Africa from ACLED.

Panel (a): events per year in sub-Saharan Africa, 1997-2025, by type (riots; protests;
organised violence = battles and violence against civilians, as in the paper).
ACLED has covered Africa since 1997; some of the rise reflects wider media coverage.
Panel (b): political-violence deaths in 2024 by world region. ACLED covers every region
from 2021, so a single recent year is comparable across regions.

Outputs: output/figures/fig_acled_africa.pdf (copied to Overleaf figures/),
         output/tables/acled_values.tex (copied to Overleaf tables/).
"""
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from config import ACLED_GLOBAL, FIGURES, TABLES, save_to_overleaf

SSA = ["Eastern Africa", "Middle Africa", "Southern Africa", "Western Africa"]
ORG = ["Battles", "Violence against civilians"]                       # paper's organised violence
POL = ["Battles", "Explosions/Remote violence", "Violence against civilians"]  # political violence (deaths panel)
GROUP = {**{r: "Sub-Saharan Africa" for r in SSA},
         "Northern Africa": "North Africa", "Middle East": "Middle East",
         "South Asia": "South Asia", "Southeast Asia": "East & Southeast Asia", "East Asia": "East & Southeast Asia",
         "Europe": "Europe", "Caucasus and Central Asia": "Central Asia & Caucasus",
         "South America": "Latin America", "Central America": "Latin America", "Caribbean": "Latin America",
         "North America": "North America", "Oceania": "Oceania", "Antarctica": None}
FIRST, LAST, YR = 1997, 2024, 2024   # the global extract (30 Mar 2026) has only part of 2025

d = pd.read_csv(ACLED_GLOBAL, usecols=["region", "year", "event_type", "fatalities"], low_memory=False)
s = d[d.region.isin(SSA) & d.year.between(FIRST, LAST)]
ts = pd.DataFrame({
    "Riots": s[s.event_type == "Riots"].groupby("year").size(),
    "Protests": s[s.event_type == "Protests"].groupby("year").size(),
    "Battles and attacks on civilians": s[s.event_type.isin(ORG)].groupby("year").size(),
}).reindex(range(FIRST, LAST + 1)).fillna(0)

w = d[(d.year == YR) & d.event_type.isin(POL)].copy()
w["grp"] = w.region.map(GROUP)
deaths = w.dropna(subset=["grp"]).groupby("grp").fatalities.sum().sort_values()
share = 100 * deaths / deaths.sum()
print(ts.loc[[FIRST, 2007, LAST]]); print(share.round(1))

fig, (a, b) = plt.subplots(1, 2, figsize=(9.5, 4.2), gridspec_kw={"width_ratios": [1.25, 1]})
col = {"Riots": "#B3261E", "Protests": "#1f5fa8", "Battles and attacks on civilians": "#555555"}
for k in ts.columns:
    a.plot(ts.index, ts[k] / 1000, color=col[k], lw=2, label=k.replace(" attacks on ", "\nattacks on\n"))
a.axvline(2007, color="#999999", ls="--", lw=0.9)
a.set_xticks([2000, 2010, 2020])
a.set_ylabel("Events per year, thousands")
a.set_title("(a) Sub-Saharan Africa, " + f"{FIRST}-{LAST}", loc="left", fontsize=10)
a.legend(frameon=False)
c = ["#B3261E" if g == "Sub-Saharan Africa" else "#9AA9AD" for g in deaths.index]
b.barh(deaths.index, deaths.values / 1000, color=c)
for i, (g, v) in enumerate(deaths.items()):
    b.text(v / 1000, i, f"  {share[g]:.0f}%", va="center", fontsize=8.5, color="#333333")
b.set_title(f"(b) Political-violence deaths by region, {YR}", loc="left", fontsize=10)
b.set_xlabel("Thousands")
for ax in (a, b):
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
fig.tight_layout()
out = FIGURES / "fig_acled_africa.pdf"
fig.savefig(out, bbox_inches="tight")
save_to_overleaf("fig_acled_africa.pdf", str(out), subfolder="figures")
plt.close(fig)

v = ["% Generated by 46_acled_descriptive.py -- do not edit by hand",
     r"\newcommand{\acledSsaDeathShare}{" + f"{share['Sub-Saharan Africa']:.0f}" + "}"]
(TABLES / "acled_values.tex").write_text("\n".join(v) + "\n", encoding="utf-8")
save_to_overleaf("acled_values.tex", str(TABLES / "acled_values.tex"), subfolder="tables")
print("saved fig_acled_africa.pdf, acled_values.tex")
