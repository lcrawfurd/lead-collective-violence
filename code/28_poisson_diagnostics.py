"""
28_poisson_diagnostics.py
Share of cells that fixed-effects Poisson drops: cells with no riot in any year carry no
information once cell fixed effects are absorbed (Appendix A).

Inputs:  output/panels/panel_{kenya,ghana,senegal}.parquet (01_build_panels.py)
Outputs: output/tables/poisson_values.tex  (\\fepDropKe, \\fepDropGh, \\fepDropSe; + Overleaf)
"""

import pandas as pd

from config import PANELS, TABLES, save_to_overleaf

print("Loading panels...")
PAN = {
    "Kenya":   pd.read_parquet(str(PANELS / "panel_kenya.parquet")),
    "Ghana":   pd.read_parquet(str(PANELS / "panel_ghana.parquet")),
    "Senegal": pd.read_parquet(str(PANELS / "panel_senegal.parquet")),
}

# Always-zero cells dropped by FE Poisson
pct_dropped = {}
for c, p in PAN.items():
    ever = p.groupby("cell_id")["n_riots"].sum()
    n_cells = len(ever)
    n_zero = int((ever == 0).sum())
    pct_dropped[c] = 100 * n_zero / n_cells
    print(f"  {c}: {n_cells} cells | always-zero (dropped by FE Poisson): "
          f"{n_zero} ({pct_dropped[c]:.0f}%)")

v = ["% Generated by 28_poisson_diagnostics.py -- do not edit by hand"]
for _c, _k in [("Kenya", "Ke"), ("Ghana", "Gh"), ("Senegal", "Se")]:
    v.append(r"\newcommand{\fepDrop" + _k + "}{" + f"{pct_dropped[_c]:.0f}" + "}")
(TABLES / "poisson_values.tex").write_text("\n".join(v) + "\n", encoding="utf-8")
save_to_overleaf("poisson_values.tex", str(TABLES / "poisson_values.tex"), subfolder="tables")
print("Saved: poisson_values.tex")
