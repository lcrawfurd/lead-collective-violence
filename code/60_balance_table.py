"""
60_balance_table.py  --  Appendix table: did places near battery sites change differently
after 2007, other than in conflict?

Panel A (satellite, cell-year): log night lights on the main design, i.e. indicators for a
  cell within 5 km of a battery site and within 5 km of a non-lead TSIP site, each x post-2007,
  in one regression with cell and country x year FE; the row is the battery minus non-lead
  coefficient, SEs clustered on 1-degree blocks, p from t(G-1). Night lights from
  output/panels/urban_controls.parquet (19_urban_controls.py).
Panels B and C (DHS): battery x post from 54_dhs_outcomes.py (output/panels/dhs_outcomes.csv), clusters
  within 5 km of a battery site v. within 5 km of another toxic site only.

Outputs: output/tables/tab_balance_changes.tex, output/tables/balance_values.tex
(both copied to Overleaf tables/).
"""
import numpy as np
import pandas as pd
import pyfixest as pf
from scipy import stats

from config import PANELS, TABLES, POST_YR, save_to_overleaf
from utils import add_block, lincom

NEAR5 = 1.0 / 6.0


def stars(p):
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.10 else ""


def num(v, d=3):
    s = f"{v:.{d}f}"
    s = "0." + "0" * d if s in ("-0." + "0" * d,) else s
    return s.replace("-", "$-$")


# ── Panel A: night lights on the main design ─────────────────────────────────
uc = pd.read_parquet(PANELS / "urban_controls.parquet")      # 19_urban_controls.py
parts = []
for cn in ["Kenya", "Ghana", "Senegal"]:
    p = pd.read_parquet(PANELS / f"panel_{cn.lower()}.parquet").merge(uc, on=["cell_id", "year"], how="left")
    p["country"] = cn
    parts.append(p)
P = add_block(pd.concat(parts, ignore_index=True), "country")
if P.log_ntl.notna().mean() < 0.99:
    raise SystemExit("60: night lights missing for more than 1% of cell-years")
P = P.dropna(subset=["log_ntl"])
P["cid"] = P.country + "_" + P.cell_id
P["cy"] = P.country + "_" + P.year.astype(str)
post = (P.year >= POST_YR).astype(int)
P["bt"] = (P.inv_dist_battery > NEAR5).astype(int) * post
P["nt"] = (P.inv_dist_nonlead > NEAR5).astype(int) * post
m = pf.feols("log_ntl ~ bt + nt | cid + cy", data=P, vcov={"CRV1": "block"})
g, se, pv = lincom(m, {"bt": 1, "nt": -1})
n_ntl = int(m._N)
print(f"night lights gap {g:.3f} ({se:.3f}) p={pv:.3f}, N={n_ntl}")

# ── Panels B, C: DHS (54) ────────────────────────────────────────────────────
R = pd.read_csv(PANELS / "dhs_outcomes.csv")
R = R[R.scope == "all"].set_index("outcome")
DHS_ROWS = [("Women aged 15--49", [("wealth_z", "Wealth index (standardised)"),
                                   ("school_yrs", "Years of schooling"),
                                   ("anaemic_w", "Anaemic (Ghana and Senegal)")]),
            ("Children and households", [("anaemic_c", "Anaemic, 6--59 months (Ghana and Senegal)"),
                                         ("hb_c", "Haemoglobin, g/dl (Ghana and Senegal)"),
                                         ("died_u5", "Died before age 5"),
                                         ("stunted", "Stunted (post-2007 rounds only)"),
                                         ("attends", "In school, ages 6--14")])]
for _, rows in DHS_ROWS:
    for k, _ in rows:
        if k not in R.index:
            raise SystemExit(f"60: {k} missing from dhs_outcomes.csv; run 54 first")

# ── Table ────────────────────────────────────────────────────────────────────
t = [r"\begin{table}[htbp]", r"\caption{Changes in Other Outcomes near Battery Sites after 2007}",
     r"\label{tab:balance_changes}", r"\begin{threeparttable}", r"\small",
     r"\begin{tabular}{lccr}", r"\toprule",
     r" & Battery $\times$ post & s.e. & $N$ \\", r"\midrule",
     r"\multicolumn{4}{l}{\textit{Panel A: Satellite data, cell-years}} \\",
     f"Log night lights & {num(g)}{stars(pv)} & ({num(se)}) & {n_ntl:,} \\\\[3pt]"]
for i, (head, rows) in enumerate(DHS_ROWS):
    t.append(r"\multicolumn{4}{l}{\textit{Panel " + "BC"[i] + f": DHS, {head.lower()}" + r"}} \\")
    for k, lab in rows:
        r = R.loc[k]
        p = 2 * stats.norm.sf(abs(r.coef / r.se))
        t.append(f"{lab} & {num(r.coef)}{stars(p)} & ({num(r.se)}) & {int(r.n):,} \\\\")
    if i == 0:
        t[-1] += "[3pt]"
t += [r"\bottomrule", r"\end{tabular}", r"\begin{tablenotes}\setstretch{1}\footnotesize",
      # Table note lives in main.tex (\setTabNote{tab_balance_changes}{...}).
      r"\item \TabNote{tab_balance_changes}", r"\end{tablenotes}", r"\end{threeparttable}", r"\end{table}"]
(TABLES / "tab_balance_changes.tex").write_text("\n".join(t) + "\n", encoding="utf-8")
save_to_overleaf("tab_balance_changes.tex", str(TABLES / "tab_balance_changes.tex"), subfolder="tables")

mac = {"balNtlGap": num(g), "balNtlP": f"{pv:.2f}"}
lines = ["% Generated by 60_balance_table.py"] + [r"\newcommand{\%s}{%s}" % kv for kv in mac.items()]
(TABLES / "balance_values.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
save_to_overleaf("balance_values.tex", str(TABLES / "balance_values.tex"), subfolder="tables")
print("saved tab_balance_changes.tex, balance_values.tex")
