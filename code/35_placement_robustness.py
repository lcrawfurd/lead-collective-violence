"""
35_placement_robustness.py

Addresses two referee concerns about identification:

(1) Site placement. If battery sites sit in systematically worse places than the
    non-lead comparison sites, the lead-specific gap could reflect selection rather
    than lead. We report the ratio of pre-2007 riot rates in battery-proximate and
    non-lead-proximate cells.

(2) 2007 cutoff / food prices. National food-price waves (2008, 2011, COVID) are
    already absorbed by country x year FE. To absorb SUB-national time shocks
    (regional food-price / poverty dynamics), we re-estimate the lead-specific gap
    adding a coarse spatial (1-degree macro-cell) x year fixed effect, and check the
    gap survives.

Outcome: extensive margin 1[any riot in cell-year], mirroring 29_extensive_margin_main.py.
Estimator: pyfixest LPM on the main binary design (within 5 km x Post), SEs clustered
on 1-degree blocks (utils.add_block), p from t(G-1). The macro-cell is the same 1-degree
cell as the cluster block.

Inputs:
  output/panels/panel_{kenya,ghana,senegal}.parquet (01_build_panels.py)
Outputs:
  output/tables/placement_values.tex           (in-text macros; \\input by main.tex; + Overleaf)
"""

import numpy as np
import pandas as pd
import pyfixest as pf

from config import PANELS, TABLES, POST_YR, save_to_overleaf
from utils import stars, add_block, lincom

NEAR = 1.0 / (5.0 + 1.0)   # 1/(d+1) threshold for "within 5 km"

# ── Load and pool the three country panels (mirror 29_extensive_margin_main) ──
PAN = {
    "Kenya":   pd.read_parquet(str(PANELS / "panel_kenya.parquet")),
    "Ghana":   pd.read_parquet(str(PANELS / "panel_ghana.parquet")),
    "Senegal": pd.read_parquet(str(PANELS / "panel_senegal.parquet")),
}

parts = []
for c, p in PAN.items():
    pp = p.copy()
    pp["post"] = (pp["year"] >= POST_YR).astype(int)
    pp["country"] = c
    pp["cell_id_str"] = c[:2] + "_" + pp["cell_id"].astype(str)
    add_block(pp, c)       # 1-degree blocks: cluster for every reported SE
    pp["cty_year"] = c + "_" + pp["year"].astype(str)
    # coarse 1-degree macro-cell (nests within country) x year
    pp["macro"] = (np.floor(pp["cell_lat"]).astype(int).astype(str) + "_"
                   + np.floor(pp["cell_lon"]).astype(int).astype(str))
    pp["macro_year"] = pp["macro"] + "_" + pp["year"].astype(str)
    parts.append(pp)
POOLED = pd.concat(parts, ignore_index=True)
print(f"Pooled: {POOLED.cell_id_str.nunique()} cells, {len(POOLED):,} obs, "
      f"{POOLED.macro.nunique()} macro-cells")


def lpm_gap(d, fe):
    """Main design: 1[any riot] on bt = 1[within 5 km of a battery site] x Post and
    nt = 1[within 5 km of a non-lead site] x Post in one regression; gap = b_bt - b_nt,
    block-clustered SE, p from t(G-1), FE spec `fe`."""
    d = d.copy()
    d["y"] = (d["n_riots"] > 0).astype(float)
    d["bat_post"] = (d["inv_dist_battery"] > NEAR).astype(int) * d["post"]
    d["nl_post"]  = (d["inv_dist_nonlead"] > NEAR).astype(int) * d["post"]
    m = pf.feols(f"y ~ bat_post + nl_post | {fe}", data=d, vcov={"CRV1": "block"})
    gap, se_gap, pval = lincom(m, {"bat_post": 1, "nl_post": -1})
    return gap, se_gap, pval, int(m._N)


# ── Point 3: finer time FE robustness on the lead-specific gap ────────────────
print("\nLead-specific gap (riots), pooled:")
g_base, s_base, p_base, n_base = lpm_gap(POOLED, "cell_id_str + cty_year")
g_fine, s_fine, p_fine, n_fine = lpm_gap(POOLED, "cell_id_str + macro_year")
print(f"  baseline (cell + country x year):     gap={g_base:.3f}{stars(p_base)} se={s_base:.3f}")
print(f"  + 1-degree macro-cell x year FE:      gap={g_fine:.3f}{stars(p_fine)} se={s_fine:.3f}")


# ── Point 2: baseline (pre-2007) riot rate, battery-near vs non-lead-near ─────
pre = POOLED[POOLED["year"] < POST_YR].copy()
pre["any_riot"] = (pre["n_riots"] > 0).astype(float)
cell = pre.groupby("cell_id_str").agg(
    inv_bat=("inv_dist_battery", "first"),
    inv_non=("inv_dist_nonlead", "first"),
    riot_rate=("any_riot", "mean"),
).reset_index()

bat_near = cell[cell.inv_bat >= NEAR]
nl_near  = cell[(cell.inv_non >= NEAR) & (cell.inv_bat < NEAR)]
print(f"\nBaseline balance: {len(bat_near)} battery-near vs {len(nl_near)} non-lead-near cells")
a, b = bat_near["riot_rate"].dropna(), nl_near["riot_rate"].dropna()
riot_ratio = a.mean() / b.mean() if b.mean() > 0 else float("nan")
print(f"  pre-2007 riot rate: battery-near {a.mean():.3f}, non-lead-near {b.mean():.3f}")

# ── Write in-text macros ──────────────────────────────────────────────────────
def money(x): return f"{x:.3f}"
vals = []
vals.append(r"% auto-generated by 35_placement_robustness.py")
vals.append(r"\newcommand{\gapBaseFE}{" + money(g_base) + r"}")
vals.append(r"\newcommand{\gapFineFE}{" + money(g_fine) + r"}")
vals.append(r"\newcommand{\balRiotRatio}{" + f"{riot_ratio:.0f}" + r"}")
vals.append(r"\newcommand{\balNBatNear}{" + f"{len(bat_near):,}" + r"}")
placement_tex = "\n".join(vals) + "\n"
(TABLES / "placement_values.tex").write_text(placement_tex, encoding="utf-8")
save_to_overleaf("placement_values.tex", str(TABLES / "placement_values.tex"), subfolder="tables")

print("\nSaved: placement_values.tex")
